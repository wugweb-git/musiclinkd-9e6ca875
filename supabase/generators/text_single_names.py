"""Generates the migration that takes "/" out of stored text on a live database.

Usage (repo root):
  python3 supabase/generators/text_single_names.py supabase/migrations/20260915140000_text_single_names.sql

The rules live in taxonomy_renames.py (TEXT, OLD_LABELS, PHRASES, KEEP), which the import generators
also apply, so a database built from the regenerated imports already holds the fixed text and this
migration changes nothing there.
"""
from __future__ import annotations

import json
import sys

from taxonomy_renames import KEEP, OLD_LABELS, PHRASES, TEXT

OUT = sys.argv[1]

whole = [{"table": t, "column": c, "old": o, "new": n} for t, cols in TEXT.items() for c, m in cols.items()
         for o, n in m.items()]
labels = [{"old": o, "new": OLD_LABELS[o]} for o in sorted(OLD_LABELS, key=len, reverse=True)]
phrases = [{"table": t, "column": c, "old": o, "new": n} for (t, c), rules in PHRASES.items() for o, n in rules]
keep = [{"table": t, "column": c} for t, c in sorted(KEEP)]
# Columns that must hold no "/" outside a URL once the rules have run (owner, 15 Sep 2026).
# taxonomy_options.metadata: every string inside it.
SLASH_FREE = [("profiles", "bio"), ("profiles", "headline"), ("feed_posts", "body"), ("portfolio_items", "title"),
              ("portfolio_items", "description"), ("studio_equipment", "name"), ("profile_business", "equipment_list"),
              ("opportunities", "role_required"), ("opportunities", "title"), ("marketplace_listings", "title"),
              ("taxonomy_options", "label"), ("taxonomy_options", "metadata")]
slash_free = [{"table": t, "column": c} for t, c in SLASH_FREE]
URL = r"(https?://|www\.)\S+"

assert all(p["column"].count(".") <= 1 for p in phrases)
assert not {(p["table"], p["column"].split(".")[0]) for p in phrases} & KEEP
assert not set(SLASH_FREE) & KEEP


def payload(rows):
    text = json.dumps(rows, ensure_ascii=False, separators=(",", ":"))
    assert "$json$" not in text
    return f"$json${text}$json$"


# Text, varchar, text[], varchar[] and jsonb columns of public base tables, except KEEP.
COLUMNS = """SELECT ic.table_name::text AS tbl, ic.column_name::text AS col,
           CASE WHEN ic.data_type IN ('text', 'character varying') THEN 'text'
                WHEN ic.data_type = 'ARRAY' THEN 'array' ELSE 'jsonb' END AS kind,
           EXISTS (SELECT 1 FROM information_schema.columns u
                   WHERE u.table_schema = 'public' AND u.table_name = ic.table_name
                     AND u.column_name = 'updated_at') AS stamped
    FROM information_schema.columns ic
    JOIN information_schema.tables tb
      ON tb.table_schema = ic.table_schema AND tb.table_name = ic.table_name AND tb.table_type = 'BASE TABLE'
    WHERE ic.table_schema = 'public' AND ic.is_generated = 'NEVER'
      AND (ic.data_type IN ('text', 'character varying', 'jsonb')
           OR (ic.data_type = 'ARRAY' AND ic.udt_name IN ('_text', '_varchar')))
      AND NOT v_keep @> jsonb_build_array(jsonb_build_object('table', ic.table_name, 'column', ic.column_name))
    ORDER BY ic.table_name, ic.ordinal_position"""

label_lines = "\n".join(f"--   {o} → {n}" for o, n in OLD_LABELS.items())
phrase_lines = "\n".join(f"--   {t}.{c}: " + " · ".join(f"“{o}” → “{n}”" for o, n in rules)
                         for (t, c), rules in PHRASES.items())
whole_lines = "\n".join(f"--   {w['table']}.{w['column']}: “{w['old']}” → “{w['new']}”" for w in whole)

sql = f"""-- Text without "/": old combined option labels and other "/" phrases in stored text.
--
-- Generated by supabase/generators/text_single_names.py from taxonomy_renames.py. Edit that and
-- regenerate, not this file. The import generators apply the same rules, so a database built from
-- the regenerated migrations already holds this text and nothing changes there.
--
-- Owner, 15 Sep 2026: no "/" in data text; keep the relevant one (a single keyword), as the taxonomy
-- labels do. Runs after 20260915110000, on every row (private profiles included).
--
-- 1. Whole values (the same fixes as 20260915110000 §5, repeated so the order below always holds):
{whole_lines}
-- 2. Old combined option labels, replaced wherever they appear inside every text, varchar, text[],
--    varchar[] and jsonb column of every public table (except taxonomy_categories.description):
{label_lines}
-- 3. Phrases, in the named column only (metadata.group is a key in taxonomy_options.metadata):
{phrase_lines}
--
-- Kept as they are: taxonomy_categories.description (internal developer notes, one names a file path)
-- and URLs anywhere. Other text columns are not rewritten beyond the rules above; the verify block
-- lists any that still hold a "/" as a NOTICE (for example cms_pages.route, which holds paths).
-- A row whose text changes gets updated_at = now() where the table has that column.
--
-- Verify (raises): no column above still holds an old label; no phrase or whole value remains in its
-- column; and no "/" outside a URL in {", ".join(f"{t}.{c}" for t, c in SLASH_FREE)}
-- (every string inside it). A "/" the rules do not cover (for example in a private profile's bio)
-- stops the migration and names the column; add a rule to taxonomy_renames.py and regenerate.
--
-- Idempotent. Rollback: not automatic; the replaced text is not kept.

-- 1-3. Replace
DO $text$
DECLARE
  v_whole jsonb := {payload(whole)};
  v_labels jsonb := {payload(labels)};
  v_phrases jsonb := {payload(phrases)};
  v_keep jsonb := {payload(keep)};
  c record;
  r record;
  v_value text;
  v_expr text;
  v_stamp text;
  v_rows bigint;
BEGIN
  FOR c IN
    {COLUMNS}
  LOOP
    -- The value rewritten: the column, each array element, or the jsonb document as text.
    v_value := CASE c.kind WHEN 'text' THEN format('t.%I', c.col) WHEN 'array' THEN 'u.x'
                           ELSE format('t.%I::text', c.col) END;
    v_expr := v_value;
    IF c.kind <> 'jsonb' THEN
      FOR r IN SELECT e.v->>'old' AS old, e.v->>'new' AS new
               FROM jsonb_array_elements(v_whole) WITH ORDINALITY AS e(v, n)
               WHERE e.v->>'table' = c.tbl AND e.v->>'column' = c.col ORDER BY e.n LOOP
        v_expr := format('CASE WHEN %s = %L THEN %L ELSE %s END', v_expr, r.old, r.new, v_expr);
      END LOOP;
    END IF;
    FOR r IN SELECT e.v->>'old' AS old, e.v->>'new' AS new
             FROM jsonb_array_elements(v_labels) WITH ORDINALITY AS e(v, n) ORDER BY e.n LOOP
      v_expr := format('replace(%s, %L, %L)', v_expr, r.old, r.new);
    END LOOP;
    IF c.kind <> 'jsonb' THEN
      FOR r IN SELECT e.v->>'old' AS old, e.v->>'new' AS new
               FROM jsonb_array_elements(v_phrases) WITH ORDINALITY AS e(v, n)
               WHERE e.v->>'table' = c.tbl AND e.v->>'column' = c.col ORDER BY e.n LOOP
        v_expr := format('replace(%s, %L, %L)', v_expr, r.old, r.new);
      END LOOP;
    END IF;

    v_stamp := CASE WHEN c.stamped AND c.col <> 'updated_at' THEN ', updated_at = now()' ELSE '' END;
    IF c.kind = 'text' THEN
      EXECUTE format('UPDATE public.%I t SET %I = %s%s WHERE t.%I <> %s',
                     c.tbl, c.col, v_expr, v_stamp, c.col, v_expr);
    ELSIF c.kind = 'array' THEN
      v_expr := format('ARRAY(SELECT %s FROM unnest(t.%I) WITH ORDINALITY AS u(x, o) ORDER BY u.o)', v_expr, c.col);
      EXECUTE format('UPDATE public.%I t SET %I = %s%s WHERE t.%I::text[] <> %s',
                     c.tbl, c.col, v_expr, v_stamp, c.col, v_expr);
    ELSE
      EXECUTE format('UPDATE public.%I t SET %I = (%s)::jsonb%s WHERE t.%I::text <> %s',
                     c.tbl, c.col, v_expr, v_stamp, c.col, v_expr);
    END IF;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    IF v_rows > 0 THEN
      RAISE NOTICE 'text single names: %.% rewritten in % rows', c.tbl, c.col, v_rows;
    END IF;
  END LOOP;

  -- Phrases under a key of a jsonb column.
  FOR r IN SELECT e.v->>'table' AS tbl, split_part(e.v->>'column', '.', 1) AS col,
                  split_part(e.v->>'column', '.', 2) AS key, e.v->>'old' AS old, e.v->>'new' AS new,
                  EXISTS (SELECT 1 FROM information_schema.columns u WHERE u.table_schema = 'public'
                          AND u.table_name = e.v->>'table' AND u.column_name = 'updated_at') AS stamped
           FROM jsonb_array_elements(v_phrases) WITH ORDINALITY AS e(v, n)
           WHERE position('.' in e.v->>'column') > 0
             AND EXISTS (SELECT 1 FROM information_schema.columns u WHERE u.table_schema = 'public'
                         AND u.table_name = e.v->>'table'
                         AND u.column_name = split_part(e.v->>'column', '.', 1) AND u.data_type = 'jsonb')
           ORDER BY e.n LOOP
    EXECUTE format('UPDATE public.%I t SET %I = jsonb_set(t.%I, ARRAY[%L], to_jsonb(replace(t.%I->>%L, %L, %L)))%s '
                   'WHERE jsonb_typeof(t.%I->%L) = ''string'' AND strpos(t.%I->>%L, %L) > 0',
                   r.tbl, r.col, r.col, r.key, r.col, r.key, r.old, r.new,
                   CASE WHEN r.stamped THEN ', updated_at = now()' ELSE '' END,
                   r.col, r.key, r.col, r.key, r.old);
  END LOOP;
END
$text$;

-- Verify
DO $verify$
DECLARE
  v_whole jsonb := {payload(whole)};
  v_labels jsonb := {payload(labels)};
  v_phrases jsonb := {payload(phrases)};
  v_keep jsonb := {payload(keep)};
  v_slash_free jsonb := {payload(slash_free)};
  v_url text := {"'" + URL + "'"};
  c record;
  r record;
  v_kind text;
  v_count bigint;
  v_bad text[] := '{{}}';
BEGIN
  -- No old label anywhere.
  FOR c IN
    {COLUMNS}
  LOOP
    EXECUTE format('SELECT count(*) FROM public.%I t WHERE EXISTS (SELECT 1 FROM jsonb_array_elements($1) AS l(v) '
                   'WHERE strpos(t.%I::text, l.v->>''old'') > 0)', c.tbl, c.col)
      INTO v_count USING v_labels;
    IF v_count > 0 THEN
      v_bad := v_bad || format('%s.%s (%s rows)', c.tbl, c.col, v_count);
    END IF;
  END LOOP;
  IF cardinality(v_bad) > 0 THEN
    RAISE EXCEPTION 'text single names: an old combined label remains in %', array_to_string(v_bad, ', ');
  END IF;

  -- No phrase or whole value remains in its column.
  FOR r IN SELECT e.v->>'table' AS tbl, split_part(e.v->>'column', '.', 1) AS col,
                  nullif(split_part(e.v->>'column', '.', 2), '') AS key, e.v->>'old' AS old, e.kind
           FROM (SELECT v, 'phrase' AS kind FROM jsonb_array_elements(v_phrases) AS p(v)
                 UNION ALL SELECT v, 'whole' FROM jsonb_array_elements(v_whole) AS w(v)) e
           WHERE EXISTS (SELECT 1 FROM information_schema.columns u WHERE u.table_schema = 'public'
                         AND u.table_name = e.v->>'table' AND u.column_name = split_part(e.v->>'column', '.', 1)) LOOP
    IF r.key IS NOT NULL THEN
      EXECUTE format('SELECT count(*) FROM public.%I t WHERE strpos(t.%I->>%L, %L) > 0', r.tbl, r.col, r.key, r.old)
        INTO v_count;
    ELSIF r.kind = 'whole' THEN
      EXECUTE format('SELECT count(*) FROM public.%I t WHERE t.%I = %L', r.tbl, r.col, r.old) INTO v_count;
    ELSE
      EXECUTE format('SELECT count(*) FROM public.%I t WHERE strpos(t.%I::text, %L) > 0', r.tbl, r.col, r.old)
        INTO v_count;
    END IF;
    IF v_count > 0 THEN
      v_bad := v_bad || format('%s.%s "%s" (%s rows)', r.tbl, coalesce(r.col || '.' || r.key, r.col), r.old, v_count);
    END IF;
  END LOOP;
  IF cardinality(v_bad) > 0 THEN
    RAISE EXCEPTION 'text single names: text still to replace in %', array_to_string(v_bad, ', ');
  END IF;

  -- No "/" outside a URL in the slash-free columns; a NOTICE for any other text column that has one.
  FOR c IN
    {COLUMNS}
  LOOP
    IF c.kind = 'text' THEN
      EXECUTE format('SELECT count(*) FROM public.%I t WHERE strpos(regexp_replace(t.%I, $1, '''', ''g''), ''/'') > 0',
                     c.tbl, c.col) INTO v_count USING v_url;
    ELSIF c.kind = 'array' THEN
      EXECUTE format('SELECT count(*) FROM public.%I t WHERE EXISTS (SELECT 1 FROM unnest(t.%I) AS u(x) '
                     'WHERE strpos(regexp_replace(u.x, $1, '''', ''g''), ''/'') > 0)', c.tbl, c.col)
        INTO v_count USING v_url;
    ELSE
      EXECUTE format('SELECT count(*) FROM public.%I t WHERE EXISTS (SELECT 1 FROM jsonb_path_query(t.%I, ''strict $.**'') AS j(v) '
                     'WHERE jsonb_typeof(j.v) = ''string'' AND strpos(regexp_replace(j.v #>> ''{{}}'', $1, '''', ''g''), ''/'') > 0)',
                     c.tbl, c.col) INTO v_count USING v_url;
    END IF;
    IF v_count > 0 THEN
      IF v_slash_free @> jsonb_build_array(jsonb_build_object('table', c.tbl, 'column', c.col)) THEN
        v_bad := v_bad || format('%s.%s (%s rows)', c.tbl, c.col, v_count);
      ELSE
        RAISE NOTICE 'text single names: %.% keeps a "/" in % rows (not a slash-free column)', c.tbl, c.col, v_count;
      END IF;
    END IF;
  END LOOP;
  IF cardinality(v_bad) > 0 THEN
    RAISE EXCEPTION 'text single names: "/" outside a URL remains in %', array_to_string(v_bad, ', ');
  END IF;

  -- Every slash-free column exists (a renamed column would otherwise pass unchecked).
  SELECT array_agg(s.v->>'table' || '.' || (s.v->>'column')) INTO v_bad
  FROM jsonb_array_elements(v_slash_free) AS s(v)
  WHERE NOT EXISTS (SELECT 1 FROM information_schema.columns u WHERE u.table_schema = 'public'
                    AND u.table_name = s.v->>'table' AND u.column_name = s.v->>'column');
  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION 'text single names: slash-free columns not found: %', array_to_string(v_bad, ', ');
  END IF;
END
$verify$;
"""

with open(OUT, "w", encoding="utf-8") as f:
    f.write(sql)
print({"whole": len(whole), "labels": len(labels), "phrases": len(phrases), "slash-free columns": len(slash_free),
       "bytes": len(sql.encode())})
