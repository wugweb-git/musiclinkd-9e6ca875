"""Generates the migration that names stored profile fields: taxonomy category profile_fields.

Usage (repo root):
  python3 supabase/generators/profile_field_labels.py supabase/migrations/20260915190000_profile_field_labels.sql

Owner, 16 Sep 2026: display names in the database for stored fields that no screen names yet, so any
screen can label them. One option per field: slug = field key, a short label from the Firebase field's
meaning, metadata {table, column} or, for a key inside profile_role_details.details, {table, column,
json_key}. Role detail keys that already have a same-named category (vocal_range, daw_tools,
availability_status, singing_styles, composition_styles) or that a screen labels through one (dj_type ->
dj_types) are not repeated here.
"""
from __future__ import annotations

import json
import re
import sys

OUT = sys.argv[1]

CATEGORY = ("profile_fields", "Profile Fields",
            "Display names for stored profile fields. slug is the field key; metadata.table and metadata.column "
            "name where it is stored, and metadata.json_key the key inside a jsonb column.")

# (table, column, json_key or None, label). Firebase field in the comment where the name differs.
FIELDS = [
    ("profile_role_details", "details", "covers_count", "Covers"),  # coversCount (singer)
    ("profile_role_details", "details", "original_songs_count", "Originals"),  # originalSongsCount (singer)
    ("profile_role_details", "details", "published_works_count", "Publications"),  # publishedWorksCount (lyricist)
    ("profile_role_details", "details", "event_experience_years", "Event Experience"),  # eventExperienceYears (dj)
    ("profile_role_details", "details", "years_of_experience", "Experience"),  # yearsOfExperience (musician)
    ("profile_role_details", "details", "primary_instrument", "Primary Instrument"),  # primaryInstrument
    ("profile_role_details", "details", "secondary_instruments", "Secondary Instruments"),  # secondaryInstruments
    ("profile_role_details", "details", "specialty", "Specialty"),  # specialty (sound_engineer)
    ("profile_role_details", "details", "specializations", "Specializations"),  # specializations (lyricist)
    ("profiles", "is_available", None, "Available"),  # isAvailable
    ("profile_business", "business_address", None, "Address"),  # businessAddress
    ("profile_business", "operating_hours", None, "Hours"),  # operatingHours
    ("profile_business", "equipment_list", None, "Equipment"),  # equipmentList
    ("profile_business", "artist_roster", None, "Artists"),  # artistRoster
    ("profile_business", "talent_roster", None, "Talent"),  # talentRoster
    ("profile_business", "courses", None, "Courses"),  # courses
    ("profile_business", "capacity", None, "Capacity"),  # capacity (venue)
    ("profile_business", "venue_features", None, "Features"),  # venueFeatures
    ("profile_business", "thumbnail_url", None, "Thumbnail"),  # brand_assets thumbnailUrl
    ("profile_business", "icon_url", None, "Icon"),  # brand_assets iconUrl
    ("portfolio_items", "likes_count", None, "Likes"),  # portfolio_projects likes
    ("portfolio_items", "views_count", None, "Views"),  # portfolio_projects projectViews
    ("portfolio_items", "shares_count", None, "Shares"),  # portfolio_projects shares
    ("profile_private", "email", None, "Email"),  # users.email
    ("profile_private", "gstin", None, "GSTIN"),  # users.gstin
    ("profile_private", "business_phone", None, "Phone"),  # studios.phone
]

options = []
for i, (table, column, json_key, label) in enumerate(FIELDS, 1):
    metadata = {"table": table, "column": column, **({"json_key": json_key} if json_key else {})}
    options.append({"category_key": CATEGORY[0], "slug": json_key or column, "label": label, "sort_order": i,
                    "metadata": metadata})
slugs = [o["slug"] for o in options]
assert len(slugs) == len(set(slugs)), "a field key is named twice"
assert all(re.fullmatch(r"[a-z0-9]+(_[a-z0-9]+)*", s) for s in slugs)
assert all("/" not in o["label"] and len(o["label"].split()) <= 2 for o in options), "labels: no /, at most two words"
assert "/" not in CATEGORY[1]


def payload(rows):
    text = json.dumps(rows, ensure_ascii=False, separators=(",", ":"))
    assert "$json$" not in text
    return f"$json${text}$json$"


columns = sorted({(t, c) for t, c, _, _ in FIELDS})
by_table: dict[str, list[str]] = {}
for t, c, k, _ in FIELDS:
    by_table.setdefault(t, []).append(k or c)

sql = f"""-- Profile field labels: display names for stored fields that no screen names yet.
--
-- Generated by supabase/generators/profile_field_labels.py. Edit that and regenerate, not this file.
-- Owner, 16 Sep 2026. Taxonomy category profile_fields ({len(options)} options): slug = field key, label = a
-- short name from the Firebase field's meaning, metadata {{"table", "column"}} and, for a key inside
-- profile_role_details.details, "json_key".
{chr(10).join(f"--   {t}: {', '.join(keys)}." for t, keys in by_table.items())}
-- Role detail keys with a same-named category keep that category's label: vocal_range, daw_tools,
-- availability_status, singing_styles, composition_styles; dj_type is labelled through dj_types.
-- trust_badges and persona_badges already have their categories and option labels.
--
-- Labels are public (taxonomy is readable by anyone); the profile_private values are not.
-- Runs after 20260915180000_private_imports_and_counts.sql, which adds the portfolio counts and private
-- columns; the last block raises if a named column does not exist. Idempotent.
--
-- Rollback:
--   DELETE FROM public.taxonomy_categories WHERE key = 'profile_fields';  -- cascades to its options

DO $import$
DECLARE
  v_category jsonb := {payload([dict(zip(("key", "label", "description"), CATEGORY))])};
  v_options jsonb := {payload(options)};
BEGIN
  INSERT INTO public.taxonomy_categories (key, label, description)
  SELECT r.key, r.label, r.description FROM jsonb_to_recordset(v_category) AS r(key text, label text, description text)
  ON CONFLICT (key) DO UPDATE SET label = EXCLUDED.label, description = EXCLUDED.description
  WHERE (taxonomy_categories.label, taxonomy_categories.description) IS DISTINCT FROM (EXCLUDED.label, EXCLUDED.description);

  INSERT INTO public.taxonomy_options (category_key, slug, label, sort_order, metadata)
  SELECT r.category_key, r.slug, r.label, r.sort_order, r.metadata
  FROM jsonb_to_recordset(v_options) AS r(category_key text, slug text, label text, sort_order int, metadata jsonb)
  ON CONFLICT (category_key, slug) DO UPDATE SET label = EXCLUDED.label, sort_order = EXCLUDED.sort_order,
    metadata = EXCLUDED.metadata
  WHERE (taxonomy_options.label, taxonomy_options.sort_order, taxonomy_options.metadata)
        IS DISTINCT FROM (EXCLUDED.label, EXCLUDED.sort_order, EXCLUDED.metadata);

  IF (SELECT count(*) FROM jsonb_to_recordset(v_category) AS r(key text, label text, description text)
      JOIN public.taxonomy_categories c ON c.key = r.key
      WHERE (c.label, c.description) IS NOT DISTINCT FROM (r.label, r.description))
     <> jsonb_array_length(v_category) THEN
    RAISE EXCEPTION 'profile_fields category: stored row differs from the payload';
  END IF;
  IF (SELECT count(*) FROM jsonb_to_recordset(v_options) AS r(category_key text, slug text, label text, sort_order int, metadata jsonb)
      JOIN public.taxonomy_options o ON o.category_key = r.category_key AND o.slug = r.slug
      WHERE (o.label, o.sort_order, o.metadata) IS NOT DISTINCT FROM (r.label, r.sort_order, r.metadata))
     <> jsonb_array_length(v_options) THEN
    RAISE EXCEPTION 'profile_fields options: stored rows differ from the payload';
  END IF;
END
$import$;

-- verify
DO $verify$
DECLARE
  v_missing text;
BEGIN
  SELECT string_agg(o.metadata->>'table' || '.' || (o.metadata->>'column'), ', ') INTO v_missing
  FROM public.taxonomy_options o
  WHERE o.category_key = 'profile_fields'
    AND NOT EXISTS (SELECT 1 FROM information_schema.columns c
                    WHERE c.table_schema = 'public' AND c.table_name = o.metadata->>'table'
                      AND c.column_name = o.metadata->>'column');
  IF v_missing IS NOT NULL THEN
    RAISE EXCEPTION 'profile_fields names a column that does not exist: %', v_missing;
  END IF;
  IF EXISTS (SELECT 1 FROM public.taxonomy_options
             WHERE category_key = 'profile_fields'
               AND (position('/' in label) > 0 OR slug IS DISTINCT FROM coalesce(metadata->>'json_key', metadata->>'column'))) THEN
    RAISE EXCEPTION 'profile_fields: a label has a / or a slug is not its field key';
  END IF;
  -- trust_badges and persona_badges: both categories exist and every stored badge has a label.
  SELECT string_agg(DISTINCT b.category || '.' || b.slug, ', ') INTO v_missing
  FROM (SELECT 'trust_badges' AS category, unnest(trust_badges) AS slug FROM public.profiles
        UNION ALL SELECT 'persona_badges', unnest(persona_badges) FROM public.profiles) b
  WHERE NOT EXISTS (SELECT 1 FROM public.taxonomy_options o WHERE o.category_key = b.category AND o.slug = b.slug);
  IF v_missing IS NOT NULL
     OR (SELECT count(*) FROM public.taxonomy_categories WHERE key IN ('trust_badges', 'persona_badges')) <> 2 THEN
    RAISE EXCEPTION 'badges without a label: %', coalesce(v_missing, 'a badge category is missing');
  END IF;
END
$verify$;
"""

with open(OUT, "w", encoding="utf-8") as f:
    f.write(sql)
print({"options": len(options), "columns": len(columns), "bytes": len(sql.encode())})
